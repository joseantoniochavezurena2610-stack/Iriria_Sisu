// backtest_2026.mjs — Did the engine warn against rainfed rice in Primera 2026?
// Run: node scripts/backtest_2026.mjs [canton-id ...]   (default: all 11 cantons)
//
// Two checks per canton, for a rainfed rice grower (loam, flat, SoilGrids pH or 6.0):
//  A. Hindcast: with the rain that actually fell in Primera 2026 (May–Aug), does the
//     engine's water balance say rainfed rice falls short?
//  B. Advice made beforehand: using ONLY data up to April 2026 and the "El Niño year"
//     scenario (the El Niño months known by then: 2023-24), does rice appear in the
//     Primera of year 1 in any of the 3 plans?
// The result is printed as it comes out, and written to docs/research/backtest-2026.md.
import { readFileSync, writeFileSync } from 'node:fs';
import { buildScenarios, SEASONS, seasonClimate } from '../web/js/climate.js';
import { recommend, waterBalance, PARAMETERS, cropsForCanton } from '../web/js/engine.js';

const load = (p) => JSON.parse(readFileSync(new URL(`../web/data/${p}`, import.meta.url)));
const crops = load('crops.json').crops;
const enso = load('enso.json');
const points = load('guanacaste/points.json').points;
let soil = null;
try { soil = load('guanacaste/soil_reference.json'); } catch { /* optional */ }
const rice = crops.find((c) => c.id === 'rice');
const ids = process.argv.slice(2).length ? process.argv.slice(2) : points.map((p) => p.id);
const priorities = { soil: 3, water: 3, risk: 4, income: 3 };
const threshold = PARAMETERS.baseFailureThreshold - 0.05 * (rice.drought_tolerance || 0);

const rows = [];
for (const id of ids) {
  const clim = load(`guanacaste/climate_${id}.json`);
  const ph = soil && soil.points && soil.points[id] && soil.points[id].phh2o ? soil.points[id].phh2o : 6.0;
  const farm = { ph, texture: 'loam', slope: 'flat', irrigation: 'none', current_crop: 'rice', organic_matter: null, max_loss_pct: null };

  // A. Hindcast with the observed Primera 2026
  const all = buildScenarios(clim, enso).scenarios;
  const s2026 = all.worst.samples.primera.find((s) => s.year === 2026);
  const s2026Primera = all.normal.samples.primera.concat(all.el_nino.samples.primera).find((s) => s.year === 2026) || s2026;
  const wb = s2026Primera ? waterBalance(rice, s2026Primera, farm) : null;
  const rain2026 = s2026Primera ? Math.round(s2026Primera.P.reduce((a, b) => a + b, 0)) : null;

  // B. Advice with data up to April 2026 only
  const before = { ...clim, months: clim.months.filter((m) => m.year < 2026 || (m.year === 2026 && m.month <= 4)) };
  const sc = buildScenarios(before, enso).scenarios;
  const local = cropsForCanton(crops, id);
  const r = recommend({ crops: local, scenarios: sc, planScenarios: Array(9).fill('el_nino'), farm, priorities });
  const primeraY1 = r.plans.map((p) => `${local[p.sequence[1]].id} (${p.profile})`);
  const riceEv = seasonClimate(sc.el_nino, SEASONS[1]);
  const riceWb = waterBalance(rice, riceEv, farm);

  rows.push({
    id, name: clim.name, ph,
    rain2026, coverage2026: wb ? wb.coverage : null, fails2026: wb ? wb.coverage < threshold : null,
    primeraY1, riceInPlans: r.plans.some((p) => local[p.sequence[1]].id === 'rice'), riceCoverageElNino: riceWb.coverage,
  });
}

const pct = (x) => (x == null ? '—' : `${Math.round(x * 100)} %`);
console.log(`Failure threshold for rainfed rice: water coverage < ${pct(threshold)}`);
console.table(rows.map((r) => ({ canton: r.name, 'rain May–Aug 2026 (mm)': r.rain2026, 'rice coverage 2026': pct(r.coverage2026), 'A: falls short?': r.fails2026, 'B: Primera y1 in plans A/B/C': r.primeraY1.join(' / '), 'B: rice proposed?': r.riceInPlans })));

